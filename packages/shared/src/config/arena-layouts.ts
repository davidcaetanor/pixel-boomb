const WALL_CHAR = "#";

/** Fora da arena conta como parede. */
export function isLayoutWall(layout: ArenaLayout, x: number, y: number): boolean {
  if (x < 0 || y < 0 || x >= ARENA_COLS || y >= ARENA_ROWS) {
    return true;
  }
  return layout.rows[y]?.[x] === WALL_CHAR;
}
